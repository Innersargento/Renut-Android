// Emits the table that joins the two keys a shader has:
//   - XenosRecomp's cache key, XXH3-64 of the whole container, and
//   - what the command processor can compute from the microcode an IM_LOAD
//     packet points at (the physical part from Shader::physicalOffset,
//     Shader::size bytes): renut::ucode::Key, which ignores the vfetch fields
//     Direct3D rewrites when it binds a vertex shader.
// Each row carries both forms of that key - with the destination swizzle and
// without - so the store can fall back to the looser one.
// Scans files for containers exactly the way XenosRecomp's main.cpp does.
//
// Containers under a folder called "internal" are stand-ins that tools/shaders/wrap_raw_ucode.py made
// from bare microcode (Direct3D's own shaders, shaders the game builds in memory): they declare no vertex
// elements, so they decode every fetch by hand. They are only for microcode that has no real container.
// When a real one shares the loose key, the stand-in is left out of the table: the runtime looks the exact
// key up first, and a stand-in captured with the exact bind-time swizzle would otherwise win over the real
// container that the loose key finds (that took the bloom pass's vertex shader away).
//
//   ucode_map <input dir> > shader_ucode_map.inc
#include <xxhash.h>

#include "xenos_ucode_key.h"

#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <map>
#include <set>
#include <vector>

static uint32_t be32(const uint8_t* p) { return (uint32_t(p[0]) << 24) | (p[1] << 16) | (p[2] << 8) | p[3]; }

int main(int argc, char** argv)
{
    struct Keys { uint64_t ucode, loose; bool standin; };
    std::map<uint64_t, Keys> entries;  // container hash -> microcode keys
    for (auto& file : std::filesystem::recursive_directory_iterator(argv[1],
             std::filesystem::directory_options::follow_directory_symlink))
    {
        if (file.is_directory())
            continue;
        bool standin = false;
        for (const auto& part : std::filesystem::relative(file.path(), argv[1]).parent_path())
            standin |= part.string() == "internal";
        std::ifstream in(file.path(), std::ios::binary);
        std::vector<uint8_t> d((std::istreambuf_iterator<char>(in)), {});
        const size_t n = d.size();
        for (size_t i = 0; n > 36 && i < n - 36 - 1;)
        {
            const uint8_t* c = d.data() + i;
            uint32_t flags = be32(c), vsize = be32(c + 4), psize = be32(c + 8);
            size_t size = size_t(vsize) + psize;
            if ((flags & 0xFFFFFF00) == 0x102A1100 && size <= n - i && be32(c + 28) == 0 && be32(c + 32) == 0)
            {
                uint64_t containerHash = XXH3_64bits(c, size);
                uint32_t shaderOffset = be32(c + 24);
                uint32_t physicalOffset = be32(c + shaderOffset), ucodeSize = be32(c + shaderOffset + 4);
                if (shaderOffset + 8 <= vsize && size_t(physicalOffset) + ucodeSize <= psize)
                {
                    const uint8_t* ucode = c + vsize + physicalOffset;
                    auto added = entries.emplace(containerHash, Keys{renut::ucode::Key(ucode, ucodeSize),
                                                                     renut::ucode::LooseKey(ucode, ucodeSize), standin});
                    // The same container found as a real file and as a stand-in is a real one.
                    if (!added.second && !standin)
                        added.first->second.standin = false;
                }
                i += size;
            }
            else
            {
                i += 4;
            }
        }
    }

    std::set<uint64_t> real_loose;
    for (auto& [container, value] : entries)
        if (!value.standin)
            real_loose.insert(value.loose);
    size_t dropped = 0;
    std::printf("// Generated by tools/shaders/ucode_map.cpp: {microcode hash, same without the destination swizzle, container hash}.\n");
    for (auto& [container, value] : entries)
    {
        if (value.standin && real_loose.count(value.loose))
        {
            ++dropped;
            continue;
        }
        std::printf("{0x%016llXull, 0x%016llXull, 0x%016llXull},\n", (unsigned long long)value.ucode, (unsigned long long)value.loose,
                    (unsigned long long)container);
    }
    std::fprintf(stderr, "%zu containers, %zu stand-ins left out (a real container has the same microcode)\n",
                 entries.size() - dropped, dropped);
}
