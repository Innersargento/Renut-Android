// Emits the table that joins the two keys a shader has:
//   - XenosRecomp's cache key, XXH3-64 of the whole container, and
//   - what the command processor can compute from the microcode an IM_LOAD
//     packet points at (the physical part from Shader::physicalOffset,
//     Shader::size bytes): renut::ucode::Key, which ignores the vfetch fields
//     Direct3D rewrites when it binds a vertex shader.
// Scans files for containers exactly the way XenosRecomp's main.cpp does.
//
//   ucode_map <input dir> > shader_ucode_map.inc
#include <xxhash.h>

#include "xenos_ucode_key.h"

#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <map>
#include <vector>

static uint32_t be32(const uint8_t* p) { return (uint32_t(p[0]) << 24) | (p[1] << 16) | (p[2] << 8) | p[3]; }

int main(int argc, char** argv)
{
    std::map<uint64_t, std::pair<uint64_t, bool>> entries;  // container hash -> (ucode hash, pixel)
    for (auto& file : std::filesystem::recursive_directory_iterator(argv[1],
             std::filesystem::directory_options::follow_directory_symlink))
    {
        if (file.is_directory())
            continue;
        std::ifstream in(file.path(), std::ios::binary);
        std::vector<uint8_t> d((std::istreambuf_iterator<char>(in)), {});
        const size_t n = d.size();
        for (size_t i = 0; n > 36 && i < n - 36 - 1;)
        {
            const uint8_t* c = d.data() + i;
            uint32_t flags = be32(c), vsize = be32(c + 4), psize = be32(c + 8);
            size_t size = size_t(vsize) + psize;
            if ((flags & 0xFFFFFF00) == 0x102A1100 && size <= n - i && be32(c + 28) == 0 && be32(c + 32) == 0)
            {
                uint64_t containerHash = XXH3_64bits(c, size);
                uint32_t shaderOffset = be32(c + 24);
                uint32_t physicalOffset = be32(c + shaderOffset), ucodeSize = be32(c + shaderOffset + 4);
                if (shaderOffset + 8 <= vsize && size_t(physicalOffset) + ucodeSize <= psize)
                {
                    uint64_t ucodeHash = renut::ucode::Key(c + vsize + physicalOffset, ucodeSize);
                    // XenosRecomp's own test for a pixel shader: the flags' low bit.
                    entries.emplace(containerHash, std::make_pair(ucodeHash, (flags & 1) != 0));
                }
                i += size;
            }
            else
            {
                i += 4;
            }
        }
    }

    std::printf("// Generated by tools/shaders/ucode_map.cpp: {microcode hash, container hash}.\n");
    for (auto& [container, value] : entries)
        std::printf("{0x%016llXull, 0x%016llXull},\n", (unsigned long long)value.first, (unsigned long long)container);
    std::fprintf(stderr, "%zu containers\n", entries.size());
}
