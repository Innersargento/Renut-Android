#!/usr/bin/env bash
# Compiles the renderer's own shaders (src/plume/shaders/*) to SPIR-V and
# writes them as C++ arrays (<name>.cpp, declared in host_shaders.h) next to the sources. Needs glslangValidator (WSL:
# apt install glslang-tools). The outputs are committed, so the Android build
# does not need glslang. A new shader also needs its declaration in host_shaders.h.
set -euo pipefail
DIR="$(cd "$(dirname "$0")/../../src/plume/shaders" && pwd)"
for src in "$DIR"/*.geom "$DIR"/*.frag "$DIR"/*.vert "$DIR"/*.comp; do
    name=$(basename "$src" | tr '.' '_')
    spv=$(mktemp)
    # Buffer references (the compute shaders) need SPIR-V 1.5.
    env=vulkan1.1; [[ "$src" == *.comp ]] && env=vulkan1.2
    glslangValidator -V --target-env "$env" -o "$spv" "$src" > /dev/null
    {
        words=$(( $(stat -c %s "$spv") / 4 ))
        echo "// Generated by tools/shaders/build_host_shaders.sh from $(basename "$src")."
        echo '#include "plume/shaders/host_shaders.h"'
        echo
        echo "const uint32_t k_${name}[$words] = {"
        od -An -v -tx4 -w16 "$spv" | sed -E 's/ ([0-9a-f]{8})/0x\1,/g'
        echo "};"
    } > "$DIR/$(basename "$src").cpp"
    rm -f "$spv"
done
