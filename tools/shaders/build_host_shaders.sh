#!/usr/bin/env bash
# Compiles the renderer's own shaders (android/rexglue/shaders/*) to SPIR-V and
# writes them as C arrays next to the sources. Needs glslangValidator (WSL:
# apt install glslang-tools). The outputs are committed, so the Android build
# does not need glslang.
set -euo pipefail
DIR="$(cd "$(dirname "$0")/../../android/rexglue/shaders" && pwd)"
for src in "$DIR"/*.geom "$DIR"/*.frag "$DIR"/*.vert "$DIR"/*.comp; do
    # Built in four variants below.
    [[ "$(basename "$src")" == native_view.vert ]] && continue
    name=$(basename "$src" | tr '.' '_')
    spv=$(mktemp)
    # Buffer references (the compute shaders) need SPIR-V 1.5.
    env=vulkan1.1; [[ "$src" == *.comp ]] && env=vulkan1.2
    glslangValidator -V --target-env "$env" -o "$spv" "$src" > /dev/null
    {
        echo "// Generated by tools/shaders/build_host_shaders.sh from $(basename "$src")."
        echo "static const uint32_t k_${name}[] = {"
        od -An -v -tx4 -w16 "$spv" | sed -E 's/ ([0-9a-f]{8})/0x\1,/g'
        echo "};"
    } > "$DIR/$(basename "$src").inc"
    rm -f "$spv"
done
# native_view.vert, with and without its texture coordinate and normal inputs:
# k_native_view_vert_t<0|1>_n<0|1>.
out="$DIR/native_view.vert.inc"
: > "$out"
for tc in 0 1; do
    for n in 0 1; do
        defines=()
        [[ $tc == 1 ]] && defines+=(-DHAS_TEXCOORD)
        [[ $n == 1 ]] && defines+=(-DHAS_NORMAL)
        spv=$(mktemp)
        glslangValidator -V --target-env vulkan1.1 "${defines[@]}" -o "$spv" "$DIR/native_view.vert" > /dev/null
        {
            echo "// Generated by tools/shaders/build_host_shaders.sh from native_view.vert (texcoord $tc, normal $n)."
            echo "static const uint32_t k_native_view_vert_t${tc}_n${n}[] = {"
            od -An -v -tx4 -w16 "$spv" | sed -E 's/ ([0-9a-f]{8})/0x,/g'
            echo "};"
        } >> "$out"
        rm -f "$spv"
    done
done
