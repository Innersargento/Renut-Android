"""Regenerates res/values*/strings.xml from strings_table.py (pt-BR is the default `values`).

Run:  python tools/i18n/gen_strings.py

Add a language: append a column to every entry in strings_table.py (and to CONTROLLER_LABELS),
a folder to `folders` below, and the language to Language.OPTIONS in Language.kt.
"""
import io
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import strings_table as st  # noqa: E402

res = os.path.normpath(os.path.join(here, '..', '..', 'android', 'app', 'src', 'main', 'res'))
# Same order as the columns of the table.
folders = ["values", "values-en", "values-zh-rCN", "values-es"]


def esc(text):
    out = (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
           .replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n"))
    if out[:1] in "@?":
        out = "\\" + out
    return out


for index, folder in enumerate(folders):
    directory = os.path.join(res, folder)
    os.makedirs(directory, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/i18n/gen_strings.py from strings_table.py; edit the table, not this file. -->',
             '<resources>']
    for key, values in st.T.items():
        lines.append('    <string name="%s">%s</string>' % (key, esc(values[index])))
    lines.append('    <string-array name="controller_labels">')
    for row in st.CONTROLLER_LABELS:
        lines.append('        <item>%s</item>' % esc(row[index]))
    lines.append('    </string-array>')
    lines.append('</resources>')
    with io.open(os.path.join(directory, "strings.xml"), "w", newline="\n", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
print(len(st.T), "strings x", len(folders), "languages")
