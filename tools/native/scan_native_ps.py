"""Finds, for each recompiled pixel shader, the texture the native view draws
with: the first 2D fetch whose coordinates are an interpolant exactly as the
vertex shader wrote it (rK = iTexCoordK, untouched, read as .xy). In the world
materials that is the surface's own texture; a shader with no such fetch (a
flat-coloured material whose only 2D texture is, say, a reflection map looked
up by a computed direction) gets none.

Writes src/d3d/native_ps_table.inc: X(hash, texture slot, interpolant).

usage: python -I tools/native/scan_native_ps.py <generated/shaders/hlsl> <out.inc>
"""
import os
import re
import sys

HASH = re.compile(r"hash=0x([0-9A-F]{16})")
INIT = re.compile(r"^float4 r(\d+) = iTexCoord(\d+);$")
FETCH = re.compile(r"tfetch2D\(texture2DDescriptorIndex\((\d+)\), samplerDescriptorIndex\(\d+\), r(\d+)\.xy,")
WRITE = re.compile(r"^r(\d+)(?:\.[xyzw]+)? =")


def scan(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    if not text.startswith("// pixel shader"):
        return None
    m = HASH.search(text.splitlines()[0])
    if not m:
        return None
    interpolant = {}  # register -> interpolant it still holds
    started = False
    for raw in text.splitlines():
        line = raw.strip()
        init = INIT.match(line)
        if init:
            interpolant[int(init.group(1))] = int(init.group(2))
            started = True
            continue
        if not started:
            continue
        fetch = FETCH.search(line)
        if fetch:
            reg = int(fetch.group(2))
            if reg in interpolant:
                return m.group(1), int(fetch.group(1)), interpolant[reg]
        w = WRITE.match(line)
        if w:
            interpolant.pop(int(w.group(1)), None)
    return None


def main():
    src, out = sys.argv[1], sys.argv[2]
    rows = []
    for name in sorted(os.listdir(src)):
        if name.startswith("ps_") and name.endswith(".hlsl"):
            row = scan(os.path.join(src, name))
            if row:
                rows.append(row)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/native/scan_native_ps.py: the surface texture of each pixel\n")
        f.write("// shader - X(hash, texture slot, interpolant its coordinates come in).\n")
        for h, slot, k in rows:
            f.write(f"X(0x{h}ull, {slot}, {k})\n")
    print(f"{len(rows)} pixel shaders")


if __name__ == "__main__":
    main()
