"""Lists the guest pixel shaders native_lit.frag stands in for: those whose
code, normalised by tools/native/permutations.py (temporaries, material
registers and literals renamed in order of first use), is the reference
permutation C139857BC4CA265A's - with or without the cascades' depth bias -
and whose literal constants are the reference's. For each, the registers that
hold its material parameters, in the reference's order: specular power,
specular colour, alpha.

Writes src/d3d/native_lit_table.inc: X(hash, power, specular, alpha, bias).

usage: python -I tools/native/lit_table.py <generated/shaders/hlsl> <out.inc>
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("permutations", os.path.join(HERE, "permutations.py"))
permutations = importlib.util.module_from_spec(spec)
spec.loader.exec_module(permutations)

REFERENCE = "C139857BC4CA265A"


def strip_bias(lines):
    """The code without the cascades' 'depth - c46' (an if (p0) block each)."""
    out, i = [], 0
    while i < len(lines):
        if (lines[i] == "if (p0)" and i + 3 < len(lines) and lines[i + 1] == "{" and "cReg(46)" in lines[i + 2]
                and lines[i + 3] == "}"):
            i += 4
            continue
        out.append(lines[i])
        i += 1
    return out


def main():
    src, out = sys.argv[1], sys.argv[2]
    shaders = {}
    for name in os.listdir(src):
        if not (name.startswith("ps_") and name.endswith(".hlsl")):
            continue
        text = open(os.path.join(src, name), encoding="utf-8", errors="replace").read()
        if not text.startswith("// pixel shader"):
            continue
        h = text.splitlines()[0].split("hash=0x")[1][:16]
        shaders[h] = permutations.normalise(text)
    ref_body, ref_material, ref_literals = shaders[REFERENCE]
    ref_lines = ref_body.split("\n")
    ref_unbiased = strip_bias(ref_lines)
    assert ref_unbiased != ref_lines, "the reference has no bias blocks"
    rows = []
    for h, (body, material, literals) in sorted(shaders.items()):
        if literals != ref_literals or len(material) != len(ref_material):
            continue
        lines = body.split("\n")
        if lines == ref_lines:
            bias = 1
        elif lines == ref_unbiased:
            bias = 0
        else:
            continue
        rows.append((h, material[0], material[1], material[2], bias))
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/native/lit_table.py: guest pixel shaders that are the permutation\n")
        f.write(f"// of {REFERENCE} native_lit.frag implements.\n")
        f.write("// X(hash, specular power register, specular colour register, alpha register, depth bias)\n")
        for h, power, specular, alpha, bias in rows:
            f.write(f"X(0x{h}ull, {power}, {specular}, {alpha}, {bias})\n")
    print(f"{len(rows)} pixel shaders")


if __name__ == "__main__":
    main()
